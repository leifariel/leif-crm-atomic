-- Kit's own answer, before anybody is invited.
--
-- The invitation machinery (20261010120000) worked out who is eligible from
-- the CRM's side: still waiting, reachable, not already applied, not already
-- a client, not Do Not Engage. What it could not know is whether KIT will
-- deliver to them — and a person who cancelled, complained, bounced or went
-- inactive is somebody who has told Kit to stop. A waitlist invitation is
-- not a reason to overrule that.
--
-- Kit holds that state and the database cannot read it, so this adds the
-- two things that let a server answer the question honestly:
--
--   a SNAPSHOT of what Kit said, per candidate, written by a read-only
--   preflight that tags nobody and enqueues nothing; and
--
--   a way to invite exactly the people in a snapshot Leif confirmed,
--   rather than re-deriving a list that may have moved underneath her.
--
-- "Oldest 25" therefore means the oldest 25 who pass BOTH checks. Somebody
-- Kit will not deliver to does not consume one of the 25 — the walk
-- continues down the list until 25 safe people are found.

-- ---------------------------------------------------------------------------
-- 1. A Kit state is its own kind of failure
-- ---------------------------------------------------------------------------
-- Not 'rejected', which means Kit refused the call, and emphatically not
-- transient: nothing about retrying changes somebody's mind about
-- unsubscribing.
alter table public.kit_sync_operations
    drop constraint if exists kit_sync_operations_failure_class_check;
alter table public.kit_sync_operations
    add constraint kit_sync_operations_failure_class_check
    check (failure_class is null or failure_class in (
        'auth', 'rejected', 'rate_limited', 'provider_unavailable',
        'network', 'not_configured', 'unsafe_state', 'unknown'));

-- ---------------------------------------------------------------------------
-- 2. What the preflight saw
-- ---------------------------------------------------------------------------
-- An audit record, not an invitation. It must never tag anybody, enqueue
-- anything, or move a waitlist place — and it holds enough for the
-- production SQL to report, independently, exactly the list Leif was shown.
create table if not exists public.waitlist_invitation_preflights (
    id bigint generated by default as identity primary key,
    offer_id bigint not null,
    cohort_id bigint,
    requested integer not null,
    resolved integer not null default 0,
    status text not null default 'open',
    created_by text,
    created_at timestamp with time zone not null default now(),
    -- Short-lived on purpose: a Kit state read an hour ago is evidence, a
    -- Kit state read last week is a guess. The worker re-checks at delivery
    -- regardless, so this bound is about what Leif is shown, not safety.
    expires_at timestamp with time zone not null default now() + interval '2 hours',
    used_at timestamp with time zone,
    batch_id bigint,
    constraint waitlist_invitation_preflights_status_check
        check (status in ('open', 'used', 'expired')),
    constraint waitlist_invitation_preflights_requested_check
        check (requested > 0)
);

alter table public.waitlist_invitation_preflights
    drop constraint if exists waitlist_invitation_preflights_offer_id_fkey;
alter table public.waitlist_invitation_preflights
    add constraint waitlist_invitation_preflights_offer_id_fkey
    foreign key (offer_id) references public.offers(id) on update cascade on delete cascade;
alter table public.waitlist_invitation_preflights
    drop constraint if exists waitlist_invitation_preflights_batch_id_fkey;
alter table public.waitlist_invitation_preflights
    add constraint waitlist_invitation_preflights_batch_id_fkey
    foreign key (batch_id) references public.waitlist_invitation_batches(id) on update cascade;

create table if not exists public.waitlist_invitation_preflight_candidates (
    id bigint generated by default as identity primary key,
    preflight_id bigint not null,
    waitlist_entry_id bigint not null,
    contact_id bigint not null,
    contact_name text,
    email text,
    joined_at timestamp with time zone,
    -- What the database said, kept even when Kit later disagrees: the two
    -- answers are different facts and collapsing them loses the reason.
    db_eligible boolean not null,
    db_exclusion_reason text,
    -- What Kit said, and when. Null state means Kit has never heard of them,
    -- which is safe — they are created at delivery through the canonical
    -- path, never here.
    kit_subscriber_id text,
    kit_state text,
    kit_checked_at timestamp with time zone,
    final_eligible boolean not null,
    exclusion_reason text,
    -- 1-based position in the final list Leif was shown. Null when excluded.
    final_rank integer,
    created_at timestamp with time zone not null default now()
);

alter table public.waitlist_invitation_preflight_candidates
    drop constraint if exists waitlist_invitation_preflight_candidates_preflight_id_fkey;
alter table public.waitlist_invitation_preflight_candidates
    add constraint waitlist_invitation_preflight_candidates_preflight_id_fkey
    foreign key (preflight_id) references public.waitlist_invitation_preflights(id)
    on update cascade on delete cascade;

create unique index if not exists waitlist_invitation_preflight_entry_idx
    on public.waitlist_invitation_preflight_candidates (preflight_id, waitlist_entry_id);
create index if not exists waitlist_invitation_preflight_final_idx
    on public.waitlist_invitation_preflight_candidates (preflight_id, final_rank);

alter table public.waitlist_invitation_preflights enable row level security;
alter table public.waitlist_invitation_preflight_candidates enable row level security;

drop policy if exists "Preflights are readable" on public.waitlist_invitation_preflights;
create policy "Preflights are readable" on public.waitlist_invitation_preflights
    for select to authenticated using (true);
drop policy if exists "Preflight candidates are readable" on public.waitlist_invitation_preflight_candidates;
create policy "Preflight candidates are readable" on public.waitlist_invitation_preflight_candidates
    for select to authenticated using (true);

-- Written only by the preflight service, which runs as service_role. The
-- browser reads them and nothing else: a snapshot the browser could write
-- would be a list Leif could be shown that nobody checked.
--
-- A table created after the security-posture migrations has no grants of
-- its own, so both roles are stated here rather than inherited.
grant select, insert, update, delete on table public.waitlist_invitation_preflights to service_role;
grant select, insert, update, delete on table public.waitlist_invitation_preflight_candidates to service_role;
revoke insert, update, delete on table public.waitlist_invitation_preflights from authenticated;
revoke insert, update, delete on table public.waitlist_invitation_preflight_candidates from authenticated;
grant select on table public.waitlist_invitation_preflights to authenticated;
grant select on table public.waitlist_invitation_preflight_candidates to authenticated;

-- ---------------------------------------------------------------------------
-- 3. Inviting exactly the people Leif confirmed
-- ---------------------------------------------------------------------------
-- Not "the oldest 25 as of now": the oldest 25 AS SHOWN. If somebody in that
-- list has become ineligible in the minutes since, they are reported and
-- left out — never quietly replaced by the next person down, who Leif never
-- saw and never agreed to.
create or replace function public.invite_from_preflight(
  p_preflight_id bigint,
  p_label text default null
) returns jsonb
language plpgsql
security definer
set search_path to 'public'
as $fn$
declare
  v_pre waitlist_invitation_preflights%rowtype;
  v_mapping kit_tag_mappings%rowtype;
  v_batch_id bigint;
  v_row record;
  v_invitation_id bigint;
  v_operation_id bigint;
  v_requested_by text;
  v_invited jsonb := '[]'::jsonb;
  v_skipped jsonb := '[]'::jsonb;
  v_taken integer := 0;
begin
  select * into v_pre from waitlist_invitation_preflights
   where id = p_preflight_id for update;
  if not found then
    return jsonb_build_object('status', 'preflight-missing');
  end if;
  if v_pre.status <> 'open' then
    -- Already used is a SUCCESS to report, not an error to retry: the batch
    -- it made is the answer.
    return jsonb_build_object('status', 'preflight-already-used',
      'batch_id', v_pre.batch_id, 'used_at', v_pre.used_at);
  end if;
  if v_pre.expires_at < now() then
    update waitlist_invitation_preflights set status = 'expired' where id = v_pre.id;
    return jsonb_build_object('status', 'preflight-expired',
      'checked_at', v_pre.created_at);
  end if;

  select * into v_mapping from kit_tag_mappings
   where offer_id = v_pre.offer_id and event = 'waitlist_invited';
  if not found then
    return jsonb_build_object('status', 'not-configured', 'offer_id', v_pre.offer_id);
  end if;

  select coalesce(s.email, btrim(s.first_name || ' ' || s.last_name))
    into v_requested_by from sales s where s.user_id = auth.uid();

  insert into waitlist_invitation_batches (offer_id, cohort_id, label, status)
  values (v_pre.offer_id, v_pre.cohort_id,
          coalesce(nullif(btrim(p_label), ''), 'Invite to apply'), 'prepared')
  returning id into v_batch_id;

  for v_row in
    select c.*
      from waitlist_invitation_preflight_candidates c
     where c.preflight_id = v_pre.id and c.final_eligible
     order by c.final_rank
  loop
    -- The database's own answer, now. Kit is re-asked at delivery by the
    -- worker; this is the CRM half, and it has to be current.
    if not exists (
      select 1 from waitlist_invitation_candidates(v_pre.offer_id, v_pre.cohort_id) j
       where j.waitlist_entry_id = v_row.waitlist_entry_id and j.eligible
    ) then
      v_skipped := v_skipped || jsonb_build_object(
        'waitlist_entry_id', v_row.waitlist_entry_id,
        'contact_id', v_row.contact_id,
        'name', v_row.contact_name,
        'reason', 'changed-since-preflight');
      continue;
    end if;

    insert into waitlist_invitations
      (batch_id, waitlist_entry_id, contact_id, status, prepared_at)
    values (v_batch_id, v_row.waitlist_entry_id, v_row.contact_id, 'prepared', now())
    returning id into v_invitation_id;

    v_operation_id := public.enqueue_kit_operation(
      v_row.contact_id, null, 'waitlist_invited', 'waitlist_invitation',
      v_mapping.kit_tag_id, v_mapping.kit_tag_name,
      coalesce(v_requested_by, 'owner'), v_invitation_id);

    if v_operation_id is null then
      update waitlist_invitations
         set status = 'failed', failed_at = now(),
             failure_reason = 'No usable email address at the moment of sending'
       where id = v_invitation_id;
      v_skipped := v_skipped || jsonb_build_object(
        'waitlist_entry_id', v_row.waitlist_entry_id,
        'contact_id', v_row.contact_id,
        'name', v_row.contact_name,
        'reason', 'no-email');
      continue;
    end if;

    v_taken := v_taken + 1;
    v_invited := v_invited || jsonb_build_object(
      'waitlist_entry_id', v_row.waitlist_entry_id,
      'contact_id', v_row.contact_id,
      'name', v_row.contact_name,
      'email', v_row.email,
      'joined_at', v_row.joined_at,
      'invitation_id', v_invitation_id,
      'operation_id', v_operation_id);
  end loop;

  if v_taken = 0 then
    delete from waitlist_invitation_batches where id = v_batch_id;
    v_batch_id := null;
  end if;

  update waitlist_invitation_preflights
     set status = 'used', used_at = now(), batch_id = v_batch_id
   where id = v_pre.id;

  return jsonb_build_object(
    'status', case when v_taken = 0 then 'nobody-eligible' else 'queued' end,
    'preflight_id', v_pre.id,
    'batch_id', v_batch_id,
    'offer_id', v_pre.offer_id,
    'kit_tag_id', v_mapping.kit_tag_id,
    'kit_tag_name', v_mapping.kit_tag_name,
    'requested', v_pre.requested,
    'queued', v_taken,
    'invited', v_invited,
    'skipped', v_skipped);
end;
$fn$;

revoke all on function public.invite_from_preflight(bigint, text) from public;
grant execute on function public.invite_from_preflight(bigint, text) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 4. Overlap, over the FINAL sets
-- ---------------------------------------------------------------------------
-- The database-only overlap (20261010120000) answered a preliminary
-- question. This one compares the two lists Leif is actually about to
-- confirm, Kit's answer included.
create or replace function public.waitlist_preflight_overlap(
  p_preflight_a bigint,
  p_preflight_b bigint
) returns table (
  contact_id_a bigint,
  contact_id_b bigint,
  name text,
  email text,
  joined_a timestamp with time zone,
  joined_b timestamp with time zone
)
language sql
stable
security definer
set search_path to 'public'
as $fn$
  select a.contact_id, b.contact_id, a.contact_name, a.email,
         a.joined_at, b.joined_at
    from waitlist_invitation_preflight_candidates a
    join waitlist_invitation_preflight_candidates b
      on b.preflight_id = p_preflight_b
     and b.final_eligible
     and (b.contact_id = a.contact_id
          or (a.email is not null and b.email is not null and b.email = a.email))
   where a.preflight_id = p_preflight_a
     and a.final_eligible
   order by a.joined_at;
$fn$;

revoke all on function public.waitlist_preflight_overlap(bigint, bigint) from public;
grant execute on function public.waitlist_preflight_overlap(bigint, bigint) to authenticated, service_role;

