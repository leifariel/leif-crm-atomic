-- AN INVITATION TO APPLY IS AN EPISODE, AND IT HAS TO END.
--
-- §4b Phase 2A: the durable Application Outreach authority. Schema only —
-- this migration creates no rows, no Opportunities, and changes no sales
-- lifecycle state.
--
-- WHAT IT IS. One invitation-to-apply episode attached to ONE Opportunity:
-- we asked this person to apply, and a follow-up window is running. The CRM
-- owns that business truth; Kit, Gmail and Instagram only execute messages
-- for it. Nothing existing could hold it — waitlist_invitations is one
-- delivery of one batch, kit_sync_operations is one external side effect,
-- deals carry a single current stage, and HANDOFF §4b forbids modelling
-- outreach as Tasks.
--
-- WHY ATTEMPTS, PLURAL. A person can be invited, go quiet, and be invited
-- again months later. That is two episodes, not one row edited twice. The
-- old attempt stays exactly as it was — the same reason waitlist_invitations
-- exists beside waitlist_entries.status, and the same append-only shape as
-- deal_stage_events and sales_call_events.
--
-- THE INVARIANT THAT MATTERS MOST. An ACTIVE attempt must always have a
-- future moment: either next_action_at, when the CRM is driving the
-- sequence, or externally_managed_until, when something else is. Without
-- that, an attempt could stay active forever and hold its Opportunity in
-- Interested forever — which is precisely the graveyard §4b was written to
-- prevent. It is a row-local fact, so a CHECK enforces it; nothing has to
-- remember to.
--
-- The 55 people invited on 11 Oct are inside live Kit automations, so their
-- attempts will be executor = 'kit' with externally_managed_until set to
-- when Kit actually stops. That date is not known yet, which is why the
-- backfill is still blocked — and why the constraint exists now rather than
-- later: it makes a boundary-less Kit attempt impossible to write, instead
-- of relying on the backfill to remember.
--
-- Deterministic and replay-safe: creates a table and its constraints, reads
-- nothing, writes no rows.

create table if not exists public.application_outreach_attempts (
    id bigint generated by default as identity primary key,

    -- The Opportunity this episode belongs to, never merely Contact+Offer:
    -- the same person may run an LE journey and a GYU journey at once, and a
    -- concluded cycle must stay concluded while a new cycle gets its own
    -- Opportunity (deals/dealActivity.ts).
    opportunity_id bigint not null,

    -- HOW THE EPISODE STARTED. Immutable provenance.
    source text not null,
    -- HOW THE NEXT MESSAGE REACHES THEM. Mutable: an Instagram-origin lead
    -- becomes reachable by email the moment Leif has an address.
    channel text not null,
    -- WHO EXECUTES THE FOLLOW-UP. 'none' means a human does, which is the
    -- honest answer for an Instagram thread with no email.
    executor text not null,

    status text not null default 'active',

    started_at timestamp with time zone not null default now(),
    -- 0 is the initial invitation; 1, 2, 3 the reminders after it.
    step smallint not null default 0,
    -- When the CRM should act next. Null while somebody else is driving.
    next_action_at timestamp with time zone,
    -- The moment an externally driven sequence is known to stop. This is the
    -- CRM-owned end of a window it does not itself execute.
    externally_managed_until timestamp with time zone,

    ended_at timestamp with time zone,
    end_reason text,

    -- Provenance, both nullable, both pointers rather than owners.
    waitlist_invitation_id bigint,
    resulting_application_id bigint,

    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),

    constraint application_outreach_attempts_source_check
        check (source in ('waitlist', 'instagram', 'manual', 'referral', 'other')),
    constraint application_outreach_attempts_channel_check
        check (channel in ('email', 'instagram', 'manual')),
    constraint application_outreach_attempts_executor_check
        check (executor in ('kit', 'gmail', 'none')),
    constraint application_outreach_attempts_status_check
        check (status in ('active', 'closed')),
    constraint application_outreach_attempts_step_check
        check (step >= 0),

    -- Materially different facts, kept materially different: not responding
    -- is not saying no, which is not unsubscribing, which is not applying.
    constraint application_outreach_attempts_end_reason_check
        check (end_reason is null or end_reason in (
            'application_submitted',
            'sequence_exhausted',
            'not_now',
            'explicit_no',
            'already_a_client',
            'email_unreachable',
            'unsubscribed',
            'do_not_engage'
        )),

    -- An episode is either running or finished, and says which without
    -- contradicting itself.
    constraint application_outreach_attempts_active_shape_check
        check (status <> 'active' or (ended_at is null and end_reason is null)),
    constraint application_outreach_attempts_closed_shape_check
        check (status <> 'closed' or (ended_at is not null and end_reason is not null)),

    -- THE ONE THAT PREVENTS A PERMANENT INTERESTED CARD: an active attempt
    -- always has a next moment, from one side or the other.
    constraint application_outreach_attempts_active_has_a_future_check
        check (status <> 'active'
               or next_action_at is not null
               or externally_managed_until is not null),

    -- And when the sequence is Kit's, the end of Kit's window is required
    -- rather than merely allowed.
    constraint application_outreach_attempts_kit_boundary_check
        check (status <> 'active' or executor <> 'kit'
               or externally_managed_until is not null)
);

-- Belongs-to-an-Opportunity, so it follows deal_stage_events / sales_calls /
-- applications: cascade. Opportunities are durable in this system (nothing
-- deletes them; exits are outcomes), so this is about referential honesty
-- rather than an expected event.
alter table public.application_outreach_attempts
    drop constraint if exists application_outreach_attempts_opportunity_id_fkey;
alter table public.application_outreach_attempts
    add constraint application_outreach_attempts_opportunity_id_fkey
    foreign key (opportunity_id) references public.deals(id)
    on update cascade on delete cascade;

-- Provenance pointers, and RESTRICT rather than the SET NULL that
-- waitlist_entries.converted_opportunity_id uses, because this provenance is
-- immutable: guard_outreach_attempt_mutation() refuses to let
-- waitlist_invitation_id change, and a cascade nulling it is exactly that
-- change arriving from the side. The honest statement is that an invitation
-- or application an episode points at cannot be deleted while the episode
-- exists — proved when resetDb tried it and the guard refused.
alter table public.application_outreach_attempts
    drop constraint if exists application_outreach_attempts_waitlist_invitation_id_fkey;
alter table public.application_outreach_attempts
    add constraint application_outreach_attempts_waitlist_invitation_id_fkey
    foreign key (waitlist_invitation_id) references public.waitlist_invitations(id)
    on update cascade on delete restrict;

alter table public.application_outreach_attempts
    drop constraint if exists application_outreach_attempts_resulting_application_id_fkey;
alter table public.application_outreach_attempts
    add constraint application_outreach_attempts_resulting_application_id_fkey
    foreign key (resulting_application_id) references public.applications(id)
    on update cascade on delete restrict;

-- ONE ACTIVE EPISODE PER OPPORTUNITY, enforced by the database rather than
-- hoped for by the caller — the same partial-unique shape
-- waitlist_entries_active_unique_idx already uses for the same kind of rule.
-- History is unlimited; only "running" is exclusive.
create unique index if not exists application_outreach_attempts_one_active_idx
    on public.application_outreach_attempts (opportunity_id)
    where status = 'active';

-- ONE EPISODE PER DELIVERED INVITATION. This is what will make the 11 Oct
-- backfill idempotent: re-running it reaches the same rows instead of
-- inviting anybody a second time.
create unique index if not exists application_outreach_attempts_one_per_invitation_idx
    on public.application_outreach_attempts (waitlist_invitation_id)
    where waitlist_invitation_id is not null;

-- Reading one Opportunity's history, newest first.
create index if not exists application_outreach_attempts_opportunity_idx
    on public.application_outreach_attempts (opportunity_id, started_at desc);

-- What the future reconciler asks: whose window has run out?
create index if not exists application_outreach_attempts_due_idx
    on public.application_outreach_attempts (next_action_at)
    where status = 'active';

comment on table public.application_outreach_attempts is
    'One invitation-to-apply episode for one Opportunity: we asked this person to apply and a follow-up window is running. The CRM owns this truth; Kit, Gmail and Instagram only execute messages for it. Many historical attempts per Opportunity, at most one active. An active attempt always has a future moment — next_action_at when the CRM drives, externally_managed_until when something else does — so it can never hold an Opportunity in Interested forever. See HANDOFF §4b.';

-- ---------------------------------------------------------------------------
-- An episode is history, and history does not change its mind
-- ---------------------------------------------------------------------------
-- CHECK constraints are row-local: they see NEW and nothing else, so they
-- cannot express "this column may not change" or "closed may not become
-- active again". Those are OLD-versus-NEW questions, and in this schema that
-- means a BEFORE UPDATE trigger — the shape
-- reject_application_response_mutation() already uses for an immutable
-- submission record, including its app.migration_mode escape hatch.
--
-- WHAT THIS PROTECTS. An Outreach attempt is the durable record of one
-- invitation episode. If its Opportunity, its source, its start or its
-- originating invitation could be rewritten, the history would say something
-- that never happened. And if a closed attempt could be set active again, a
-- second outreach cycle would overwrite the first instead of standing beside
-- it — which is exactly what §4b says must not happen. A genuinely new cycle
-- is a NEW row.
--
-- IT ALSO MAINTAINS updated_at. Everywhere else in this schema updated_at is
-- written by whoever happens to be doing the UPDATE, and
-- waitlist_entries.updated_at proves how that ends: it still read 2026-09-17
-- on a row whose status had changed that same day, and a zero-mutation proof
-- built on it was wrong. A column that looks authoritative and is not is
-- worse than no column, so this one is set by the database on every update
-- and never trusted from the caller.
create or replace function public.guard_outreach_attempt_mutation()
returns trigger
language plpgsql
set search_path to 'public'
as $$
begin
  -- The backfill of the 11 Oct invitations runs as a migration and may need
  -- to correct what it wrote; the same hatch every other guard here uses.
  if current_setting('app.migration_mode', true) = 'true' then
    return new;
  end if;

  if new.id is distinct from old.id
     or new.opportunity_id is distinct from old.opportunity_id
     or new.source is distinct from old.source
     or new.started_at is distinct from old.started_at
     or new.waitlist_invitation_id is distinct from old.waitlist_invitation_id
     or new.created_at is distinct from old.created_at
  then
    raise exception
      'application_outreach_attempts: identity and provenance are immutable'
      using hint = 'id, opportunity_id, source, started_at, waitlist_invitation_id and created_at describe an episode that already happened. A different Opportunity, source or invitation is a different episode: insert a new attempt.';
  end if;

  if old.status = 'closed' then
    raise exception
      'application_outreach_attempts: a closed attempt is history and cannot be changed'
      using hint = 'Re-inviting somebody starts a NEW attempt beside this one. Closed attempts are never reopened, so the record of what was tried before survives.';
  end if;

  -- Set by the database, never taken from the caller.
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists guard_outreach_attempt_mutation on public.application_outreach_attempts;
create trigger guard_outreach_attempt_mutation
  before update on public.application_outreach_attempts
  for each row execute function public.guard_outreach_attempt_mutation();

-- ---------------------------------------------------------------------------
-- Security
-- ---------------------------------------------------------------------------
-- This authority will eventually cause real emails to real people, so it gets
-- the conservative posture of waitlist_invitation_preflights rather than the
-- permissive one older CRM tables carry: readable by the owner, writable by
-- nobody through the table itself.
--
-- No runtime writer exists yet, and deliberately so. Lifecycle transitions
-- belong in authoritative functions that can check the invariants, not in
-- arbitrary client UPDATEs — so no general-purpose write surface is opened
-- here just because one will eventually be needed.
alter table public.application_outreach_attempts enable row level security;

drop policy if exists "Outreach attempts are readable" on public.application_outreach_attempts;
create policy "Outreach attempts are readable"
    on public.application_outreach_attempts
    for select to authenticated using (true);

grant select on table public.application_outreach_attempts to authenticated;
revoke insert, update, delete on table public.application_outreach_attempts from authenticated;
revoke all on table public.application_outreach_attempts from anon;
revoke all on table public.application_outreach_attempts from public;
grant select, insert, update, delete on table public.application_outreach_attempts to service_role;
